#!/usr/bin/env python3
"""Generate tests/ARCHIVE/BACKFILL-TEST-RUNS.md from the local daily work logs.

The daily logs under .workbuddy/memory/ are deliberately gitignored. Before
2026-11-24 they were the only place where many test procedures and results were
written down; this script copies the test-related lines into a versioned
archive, redacts credentials, and resolves referenced evidence files with size
and sha256 so an ignored raw report is still traceable.

Generated file is deterministic; do not hand-edit it. Re-run after a daily log
is amended:
    python3 scripts/build_test_archive_backfill.py
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]
MEMORY_DIR = ROOT / ".workbuddy" / "memory"
OUT = ROOT / "tests" / "ARCHIVE" / "BACKFILL-TEST-RUNS.md"

TEST_HINT = re.compile(
    r"(?:测试|复跑|回归|实验|探针|probe|e2e|cargo test|抓包|验证|压测|实测|PASS|BLOCKED|SKIPPED|FAILED)",
    re.IGNORECASE,
)
BULLET = re.compile(r"^\s*(?:[-*+]|\d+\.)\s+")
PATH = re.compile(r"`([^`]+\.(?:json|jsonl|txt|log|pcap|png|zip|md|bin|sha256|toml))`")
SECRET = re.compile(
    r"(?i)(密码|password|passwd|secret|token|ECPassword)"
    r"(?:明文)?\s*[=:：]?\s*(?:`[^`]*`|\S+)",
)
PHRASE_SECRET = re.compile(
    r"(?i)(密码|password)\s+(?:是|为|明文)\s+\S+"
)


def redact(line: str) -> str:
    line = SECRET.sub(lambda m: m.group(1) + "=<redacted>", line)
    # Catch the `password is ABC123` spelling that has no delimiter before it.
    line = PHRASE_SECRET.sub(r"\1 <redacted>", line)
    # Some logs spell it "密码明文 `value`"; the optional "明文" above covers it,
    # but a second pass removes any backticked value that survived.
    line = re.sub(r"(?i)(密码|password|secret|token)(明文)?\s+`[^`]+`",
                  r"\1\2=<redacted>", line)
    return line


def digest(path: pathlib.Path) -> tuple[str, int]:
    h = hashlib.sha256()
    size = 0
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            h.update(chunk)
            size += len(chunk)
    return h.hexdigest(), size


def main() -> int:
    try:
        tracked = set(
            subprocess.check_output(
                ["git", "-C", str(ROOT), "ls-files", "-z"], stderr=subprocess.DEVNULL
            ).decode("utf-8", "replace").split("\0")
        )
    except (OSError, subprocess.CalledProcessError):
        tracked = set()

    hash_cache: dict[pathlib.Path, tuple[str, int]] = {}
    out: list[str] = [
        "# Backfilled test-run archive (daily logs)",
        "",
        "> Generated by `scripts/build_test_archive_backfill.py` from the gitignored",
        "> `.workbuddy/memory/YYYY-MM-DD.md` work logs. It preserves the original",
        "> test procedure/result lines, redacts credentials, and binds referenced",
        "> evidence files to size + sha256 even when the raw file stays gitignored.",
        "> `log-only` means no durable raw evidence path was recorded at the time;",
        "> do not promote such an entry to gate evidence retroactively.",
        "",
    ]

    for log in sorted(MEMORY_DIR.glob("2026-11-*.md")):
        date = log.stem
        log_hash, _ = digest(log)
        lines = [
            redact(raw.strip())
            for raw in log.read_text(encoding="utf-8").splitlines()
            if TEST_HINT.search(raw) and BULLET.match(raw)
        ]
        if not lines:
            continue
        out += [f"## {date}", "", f"- source: `.workbuddy/memory/{date}.md` "
                f"(sha256 `{log_hash}`)", f"- archived test-related lines: {len(lines)}", ""]
        for line in lines:
            out.append(f"- {line}")
            refs = []
            for raw_path in PATH.findall(line):
                if not raw_path.startswith(("tests/", "reports/", "docs/", "dist/")):
                    continue
                target = ROOT / raw_path
                if not target.is_file():
                    refs.append(f"`{raw_path}` — MISSING")
                    continue
                if target not in hash_cache:
                    hash_cache[target] = digest(target)
                sha, size = hash_cache[target]
                in_git = "in git" if raw_path in tracked else "local/gitignored"
                refs.append(f"`{raw_path}` — {size} B, sha256 `{sha}`, {in_git}")
            if refs:
                out.append("  - evidence:")
                out.extend(f"    - {ref}" for ref in refs)
            elif any(word in line for word in ("测试", "复跑", "实验", "probe", "e2e", "cargo test")):
                out.append("  - evidence: log-only (no durable raw path recorded)")
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT).as_posix()}: {len(out)} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
